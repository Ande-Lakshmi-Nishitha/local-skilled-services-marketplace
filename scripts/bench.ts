// Index benchmarks, in a throw-away schema "bench" (your real data is not touched).
//   1. Availability lookup ("next 5 open slots of worker X") on many slots: no index vs plain vs partial index
//   2. Vector search on many 384-dim vectors: exact scan vs HNSW at several ef_search values (latency + recall@10)
//
//   npm run bench                                    defaults: 300 000 slots, 20 000 vectors
//   npm run bench -- --slots 1000000 --vectors 50000
// Results: terminal + docs/evidence/bench-results.md
import './_env';
import { mkdirSync, writeFileSync } from 'node:fs';
import { Client } from 'pg';

const arg = (n: string, d: number) => { const i = process.argv.indexOf(`--${n}`); return i > 0 ? Number(process.argv[i + 1]) : d; };
const SLOTS = arg('slots', 300_000);
const VECTORS = arg('vectors', 20_000);
const RUNS = 40;

const lines: string[] = [];
const out = (s = '') => { console.log(s); lines.push(s); };

async function timeQuery(c: Client, sql: string, params: unknown[][]): Promise<{ ms: number; plan: string }> {
  const times: number[] = [];
  let plan = '';
  for (const p of params) {
    const { rows } = await c.query(`EXPLAIN (ANALYZE, FORMAT JSON) ${sql}`, p);
    const j = rows[0]['QUERY PLAN'][0];
    times.push(j['Execution Time']);
    if (!plan) {
      const names: string[] = [];
      const walk = (n: { 'Node Type': string; 'Index Name'?: string; Plans?: unknown[] }) => {
        names.push(n['Index Name'] ? `${n['Node Type']} (${n['Index Name']})` : n['Node Type']);
        (n.Plans as typeof n[] | undefined)?.forEach(walk);
      };
      walk(j.Plan);
      plan = names.join(' > ');
    }
  }
  times.sort((a, b) => a - b);
  return { ms: times[Math.floor(times.length / 2)], plan };
}

async function main() {
  const c = new Client({ connectionString: process.env.POSTGRES_URL });
  await c.connect();
  await c.query('DROP SCHEMA IF EXISTS bench CASCADE');
  await c.query('CREATE SCHEMA bench');
  out('# Index benchmarks');
  out();
  out(`Generated by \`npm run bench\` on ${new Date().toISOString().slice(0, 10)}. Times are medians of ${RUNS} EXPLAIN ANALYZE runs with random parameters.`);

  // ------------------------------------------------------------------ 1. slots
  const workers = Math.max(10, Math.round(SLOTS / 100));
  console.log(`\nbuilding ${SLOTS} slots for ${workers} workers...`);
  await c.query(`CREATE TABLE bench.slot (slot_id serial PRIMARY KEY, worker_id int NOT NULL, start_time timestamptz NOT NULL,
                 end_time timestamptz NOT NULL, status text NOT NULL)`);
  await c.query(`INSERT INTO bench.slot (worker_id, start_time, end_time, status)
    SELECT 1 + (g % $2), now() - interval '60 days' + (g / $2) * interval '3 hours',
           now() - interval '60 days' + (g / $2) * interval '3 hours' + interval '2 hours',
           CASE WHEN random() < 0.6 THEN 'open' WHEN random() < 0.8 THEN 'reserved' ELSE 'blocked' END
    FROM generate_series(0, $1 - 1) g`, [SLOTS, workers]);
  await c.query('ANALYZE bench.slot');
  const sq = `SELECT slot_id, start_time FROM bench.slot WHERE worker_id = $1 AND status = 'open' AND start_time > now() ORDER BY start_time LIMIT 5`;
  const params = Array.from({ length: RUNS }, () => [1 + Math.floor(Math.random() * workers)]);

  const r0 = await timeQuery(c, sq, params);
  await c.query('CREATE INDEX bench_slot_worker ON bench.slot (worker_id)');
  await c.query('ANALYZE bench.slot');
  const r1 = await timeQuery(c, sq, params);
  await c.query('DROP INDEX bench.bench_slot_worker');
  await c.query(`CREATE INDEX bench_slot_partial ON bench.slot (worker_id, start_time) WHERE status = 'open'`);
  await c.query('ANALYZE bench.slot');
  const r2 = await timeQuery(c, sq, params);
  const size = async (n: string) => (await c.query(`SELECT pg_size_pretty(pg_relation_size($1::regclass)) AS s`, [n])).rows[0].s;

  out();
  out(`## 1. Availability lookup: "next 5 open slots of a worker" (${SLOTS.toLocaleString()} slots, ${workers.toLocaleString()} workers)`);
  out();
  out('```sql');
  out(sq);
  out('```');
  out();
  out('| index | median time | plan |');
  out('|---|---|---|');
  out(`| none | ${r0.ms.toFixed(2)} ms | ${r0.plan} |`);
  out(`| plain (worker_id) | ${r1.ms.toFixed(2)} ms | ${r1.plan} |`);
  out(`| partial (worker_id, start_time) WHERE status = 'open' - the one in migration 001 (${await size('bench.bench_slot_partial')}) | ${r2.ms.toFixed(2)} ms | ${r2.plan} |`);

  // ------------------------------------------------------------------ 2. vectors
  console.log(`\nbuilding ${VECTORS} random 384-dim vectors in 50 clusters...`);
  await c.query('CREATE TABLE bench.vec (id serial PRIMARY KEY, embedding vector(384) NOT NULL)');
  await c.query(`CREATE TABLE bench.center AS SELECT c, array_agg(random() - 0.5 ORDER BY d) AS v FROM generate_series(1, 50) c, generate_series(1, 384) d GROUP BY c`);
  for (let done = 0; done < VECTORS; done += 5000) {
    const n = Math.min(5000, VECTORS - done);
    await c.query(`INSERT INTO bench.vec (embedding)
      SELECT (SELECT array_agg(x + (random() - 0.5) * 0.6 ORDER BY ord) FROM unnest(ce.v) WITH ORDINALITY AS u(x, ord))::vector
      FROM generate_series(1, $1) g JOIN bench.center ce ON ce.c = 1 + (g % 50)`, [n]);
  }
  await c.query(`UPDATE bench.vec SET embedding = l2_normalize(embedding)`).catch(async () => {
    // pgvector < 0.7 has no l2_normalize; cosine distance does not need normalised vectors anyway
  });
  await c.query('ANALYZE bench.vec');
  const { rows: qs } = await c.query(`SELECT embedding::text AS e FROM bench.vec ORDER BY random() LIMIT ${RUNS}`);
  const vq = 'SELECT id FROM bench.vec ORDER BY embedding <=> $1::vector LIMIT 10';

  // exact answers + latency (no index exists yet)
  const exact: number[][] = [];
  const exactTimes: number[] = [];
  for (const q of qs) {
    const t = performance.now();
    exact.push((await c.query(vq, [q.e])).rows.map((r) => r.id));
    exactTimes.push(performance.now() - t);
  }
  const exactPlan = await timeQuery(c, vq, qs.slice(0, 10).map((q) => [q.e]));

  console.log('building HNSW index...');
  const tb = Date.now();
  await c.query('CREATE INDEX bench_vec_hnsw ON bench.vec USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64)');
  const buildS = (Date.now() - tb) / 1000;

  out();
  out(`## 2. Vector search: top-10 by cosine distance (${VECTORS.toLocaleString()} vectors x 384 dims)`);
  out();
  out(`HNSW index (m = 16, ef_construction = 64) built in ${buildS.toFixed(1)} s, size ${await size('bench.bench_vec_hnsw')}.`);
  out();
  out('| method | median query time | recall@10 vs exact | plan |');
  out('|---|---|---|---|');
  exactTimes.sort((a, b) => a - b);
  out(`| exact (sequential scan) | ${exactPlan.ms.toFixed(2)} ms | 100% | ${exactPlan.plan} |`);
  for (const ef of [10, 40, 100, 200]) {
    await c.query(`SET hnsw.ef_search = ${ef}`);
    let hits = 0;
    for (let i = 0; i < qs.length; i++) {
      const got = (await c.query(vq, [qs[i].e])).rows.map((r) => r.id);
      hits += got.filter((id) => exact[i].includes(id)).length;
    }
    const t = await timeQuery(c, vq, qs.map((q) => [q.e]));
    out(`| HNSW, ef_search = ${ef} | ${t.ms.toFixed(2)} ms | ${((hits / (qs.length * 10)) * 100).toFixed(1)}% | ${t.plan} |`);
  }
  await c.query('RESET hnsw.ef_search');

  await c.query('DROP SCHEMA bench CASCADE');
  await c.end();
  mkdirSync('docs/evidence', { recursive: true });
  writeFileSync('docs/evidence/bench-results.md', lines.join('\n') + '\n');
  console.log('\nSaved to docs/evidence/bench-results.md (the bench schema was dropped)');
}

main().catch((err) => { console.error(err); process.exit(1); });
